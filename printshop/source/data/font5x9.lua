--   <char> <row0> <row1> ... <rowN>
--
-- Rows are 5 characters of '#' (ink) or '.' (paper). Missing trailing rows
-- are blank. A handful of control bytes are repurposed as icon glyphs; see
-- FontGlyphs.icons below for the names used by the rest of the code.
--
-- The table is parsed once at startup by components/text.lua.

