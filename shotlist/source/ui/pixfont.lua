-- Pre-compute horizontal runs per glyph row: { {row, x, len}, ... }
local RUNS, WIDTH = {}, {}
for ch, rows in pairs(G) do
	local runs = {}
	WIDTH[ch] = #rows[1]
	for r, line in ipairs(rows) do
		local x = 1
		while x <= #line do
			if line:sub(x, x) == "#" then
				local s = x
				while x <= #line and line:sub(x, x) == "#" do x = x + 1 end
				runs[#runs + 1] = { r - 1, s - 1, x - s }
			else
				x = x + 1
			end
		end
	end
	RUNS[ch] = runs
end

Pixfont.HEIGHT = 7

local function norm(s)
	s = Util.upper(s or "")
	s = s:gsub("\194\176", "\176") -- UTF-8 degree -> single byte glyph key
	return s
end

function Pixfont.width(s, scale)
	s = norm(s)
	scale = scale or 1
	local w = 0
	for i = 1, #s do
		local ch = s:sub(i, i)
		w = w + (WIDTH[ch] or WIDTH["?"]) + 1
	end
	if w > 0 then w = w - 1 end
	return w * scale
end

-- Draw with the current color. align: "left" | "center" | "right".
function Pixfont.draw(s, x, y, scale, align)
	s = norm(s)
	scale = scale or 1
	if align == "center" then x = x - Pixfont.width(s, scale) // 2
	elseif align == "right" then x = x - Pixfont.width(s, scale) end
	local gfx = playdate.graphics
	local cx = x
	for i = 1, #s do
		local ch = s:sub(i, i)
		local runs = RUNS[ch] or RUNS["?"]
		for _, r in ipairs(runs) do
			gfx.fillRect(cx + r[2] * scale, y + r[1] * scale, r[3] * scale, scale)
		end
		cx = cx + ((WIDTH[ch] or WIDTH["?"]) + 1) * scale
	end
	return cx - x - scale
end

-- Largest scale (<= maxScale) at which s fits in maxW.
function Pixfont.fitScale(s, maxW, maxScale, minScale)
	local sc = maxScale
	while sc > (minScale or 1) and Pixfont.width(s, sc) > maxW do sc = sc - 1 end
	return sc
end

-- Truncate s so it fits at scale.
function Pixfont.fit(s, maxW, scale)
	s = norm(s)
	if Pixfont.width(s, scale) <= maxW then return s end
	while #s > 1 and Pixfont.width(s .. ".", scale) > maxW do s = s:sub(1, -2) end
	return s .. "."
end

return Pixfont
